/// 根据 palette 索引和 quote 索引获取渐变三元组
pub fn get_gradient(palette: u8, idx: usize) -> GradientTriple {
    let i = idx % 16;
    match palette % 8 {
        0 => PALETTE_MIDNIGHT[i],
        1 => PALETTE_DARK[i],
        2 => PALETTE_LIGHT[i],
        3 => PALETTE_NORD[i],
        4 => PALETTE_MONOKAI[i],
        5 => PALETTE_TERMINAL[i],
        6 => PALETTE_ANTHROPIC_LIGHT[i],
        _ => PALETTE_ANTHROPIC_DARK[i],
    }
}
